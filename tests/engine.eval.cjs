const Core = require('../app/core.js');
const LEX = require('../public/data/lexicon.json');

const ac = Core.buildAC(Core.buildPatterns(LEX.entries));
function hitWords(text) { return Core.matchText(text, ac).map((h) => h.p.item.word); }

